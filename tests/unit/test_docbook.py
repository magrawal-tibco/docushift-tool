def test_a_page_that_already_has_a_heading_gains_no_second_one(tmp_path: Path) -> None:
    body = one_page(tmp_path, "<p>Body.</p>").body("authoring/topic.md")

    assert body.startswith("# Topic\n")
    assert body.count("# Topic") == 1


# -- the class vocabulary (§5.6.7) ----------------------------------------------


def test_every_admonition_class_maps_and_the_printed_label_is_deleted(tmp_path: Path) -> None:
    """The class is the kind and the `h3.title` is the label GFM draws itself."""
    body = one_page(tmp_path, "".join(
        f'<div class="{kind}"><h3 class="title">{kind.title()}</h3>'
        f"<p>{kind} text.</p></div>"
        for kind in ("note", "tip", "important", "warning", "caution")
    )).body("authoring/topic.md")

    for kind in ("NOTE", "TIP", "IMPORTANT", "WARNING", "CAUTION"):
        assert f"> [!{kind}]" in body
    assert "### Note" not in body
    assert "ALERT_LABEL_UNMAPPED" not in body


def test_a_mapped_span_is_unwrapped_before_it_is_wrapped(tmp_path: Path) -> None:
    """3,145 `span.bold` contain a `strong`; `**` around `**` renders `****`."""
    body = one_page(tmp_path, (
        '<p><span class="bold"><strong>Save</strong></span> and '
        '<span class="command"><strong>sbd</strong></span> and '
        '<span class="emphasis"><em>maybe</em></span>.</p>'
    )).body("authoring/topic.md")

    assert "**Save**" in body and "****" not in body
    assert "`sbd`" in body
    # `span.emphasis` is never mapped: its `em` already says it.
    assert "*maybe*" in body and "**maybe**" not in body


def test_a_media_object_table_is_layout_and_is_unwrapped(tmp_path: Path) -> None:
    """1,126 single-cell tables wrapped around one image, purely for centring."""
    result = one_page(tmp_path, (
        '<div class="mediaobject"><table border="0" summary="manufactured viewport">'
        '<tr><td><img alt="Flow" src="../images/flow.png"/></td></tr></table></div>'
    ), {"html/images/flow.png": "PNG"})
    body = result.body("authoring/topic.md")

    assert "![Flow](" in body
    assert "|" not in body


def test_a_simplelist_table_becomes_a_list(tmp_path: Path) -> None:
    """192 of them: rows of one or two cells holding a link or a code span."""
    body = one_page(tmp_path, (
        '<table class="simplelist" border="0" summary="Simple list">'
        "<tr><td>alpha</td><td>beta</td></tr><tr><td>gamma</td><td></td></tr></table>"
    )).body("authoring/topic.md")

    assert "- alpha" in body and "- beta" in body and "- gamma" in body
    assert "|" not in body


def test_a_figure_caption_precedes_its_content_in_italic(tmp_path: Path) -> None:
    """`div.figure` is `a + p.title + div.figure-contents`, caption first."""
