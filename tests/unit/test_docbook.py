"""Unit tests for the DocBook engine (planning.md Phase 5e).

Every fixture is a miniature version tree -- `html/` with a guide or two under it
-- because that is the unit the engine works in, and because most of
`architecture.md` §5.6's rules are only visible at that scale: whether a directory
is the root depends on where its stylesheet link lands, whether an anchor survives
depends on whether anything else points at it, and whether a page is navigable
depends on what its guide's book page links to.

The assertions are on the *corpus's* rules rather than on DocBook in general, and
the tests that look oddly specific are the ones where the tempting implementation
is wrong on real input:

- a duplicate directory is rejected on its stylesheet link, because it holds
  DocBook pages too and "holds a DocBook page" converts eight guides twice;
- `span.bold` is unwrapped before it is bolded, because 3,145 of them already
  contain a `strong` and `**` around `**` is `****`;
- the legal page comes from `div#footer`, because `is_legal_label` matches "third
  party" and `apiguide/thirdpartylibs.html` is a topic about packaging JARs;
- `a.ix` is dropped whole, because its `name` is prose with spaces and 0 of 3,347
  are ever referenced.
"""

from collections.abc import Mapping
from pathlib import Path

from docushift.engines.base import ConversionContext, Unit
from docushift.engines.docbook import CONTENT_ID, DocBookEngine
from docushift.engines.roots import find_output_roots
from docushift.models import SourceEngine
from docushift.reporting.findings import FindingsRun
from docushift.transforms.assets import AssetCopier

# -- fixtures in the small ------------------------------------------------------

MENU = (
    ("Welcome", "welcome/index.html"),
    ("Authoring", "authoring/index.html"),
)


def build(directory: Path, files: Mapping[str, str]) -> Path:
    for name, text in files.items():
        path = directory / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return directory


def page(relative: str, title: str, body: str = "<p>Body.</p>", *,
         menu: tuple[tuple[str, str], ...] = MENU, footer: bool = True) -> str:
    """One page as DocBook XSL publishes it: generator comment, chrome, container.

    The chrome is real and it is all *outside* `div#mainContent`, which is the
    whole of §5.6.4: selecting the container is the chrome removal, so a test that
    left the chrome out would prove nothing.
    """
    up = "../" * (relative.count("/"))
    tabs = "".join(
        f'<span class="otherbook"><a href="{up}{href}">{label}</a></span>'
        for label, href in menu
    )
    footer_html = (
        '<div id="footer"><div id="user-footer"><ul>'
        f'<li id="legal-and-third-party-notices">'
        f'<a href="{up}welcome/legal-and-third-party-notices.html">Copyright</a> (c) 2026</li>'
        f'<li id="contact"><a href="{up}welcome/contact.html">Contact Us</a></li>'
        "</ul></div></div>"
    ) if footer else ""
    return (
        "<html><head>"
        "<!-- Generated by DocBook XSL Stylesheets V1.76.1 -->"
        '<meta http-equiv="Content-Type" content="text/html; charset=utf-8"/>'
        f"<title>{title}</title>"
        f'<link rel="stylesheet" href="{up}css/sbhelp.css" type="text/css"/>'
        "</head><body>"
        '<div id="header"><div id="banner">TIBCO StreamBase</div></div>'
        f'<p id="mainhelp-navmenu"><span class="currentbook">'
        f'<a href="{up}index.html">Home</a></span>{tabs}</p>'
        '<div id="breadcrumbs">You are here</div>'
        f'<div id="{CONTENT_ID}">{body}</div>'
        f"{footer_html}"
        "</body></html>"
    )


def titlepage(title: str) -> str:
    """The `div.titlepage` wrapper every generated page opens with."""
    return (
        '<div class="titlepage"><div><div>'
        f'<h1 class="title"><a name="{title.lower().replace(" ", "-")}"></a>{title}</h1>'
        "</div></div></div>"
    )


def toc(entries: str) -> str:
    return f'<div class="toc"><p><b>Contents</b></p><dl>{entries}</dl></div>'


def entry(href: str, label: str, children: str = "") -> str:
    nested = f'<dd><dl>{children}</dl></dd>' if children else ""
    return f'<dt><span class="article"><a href="{href}">{label}</a></span></dt>{nested}'


def javadoc(title: str) -> str:
    return (
        "<html><head><!-- Generated by javadoc (17) -->"
        f"<title>{title}</title></head><body><h1>{title}</h1></body></html>"
    )


# -- running one tree -----------------------------------------------------------


class Run:
    """One conversion of one extracted tree, with its units and its findings."""

    def __init__(self, units: list[Unit], findings: FindingsRun, tree: Path):
        self.units = units
        self.findings = findings
        self.tree = tree

    @property
    def unit(self) -> Unit:
        return self.units[0]

    def document(self, relative: str):
        for document in self.unit.documents:
            if str(document.relative) == relative:
                return document
        raise AssertionError(f"{relative} not among {self.names()}")

    def body(self, relative: str) -> str:
        return self.document(relative).body

    def names(self) -> list[str]:
        return sorted(str(d.relative) for d in self.unit.documents)

    def codes(self) -> dict[str, int]:
        tally: dict[str, int] = {}
        for finding in self.findings.all:
            tally[finding.code] = tally.get(finding.code, 0) + finding.count
        return tally

    def messages(self, code: str) -> list[str]:
        return [f.message for f in self.findings.all if f.code == code]

    def labels(self) -> list[str]:
        return [node.label for node in self.unit.nav]

    def under(self, label: str) -> list[str]:
        for node in self.unit.nav:
            if node.label == label:
                return [child.label for child in node.children]
        raise AssertionError(f"{label} not among {self.labels()}")


def run(tmp_path: Path, files: Mapping[str, str], api_roots: list[str] | None = None) -> Run:
    """Converts every unit in a tree, the way the driver does."""
    tree = build(tmp_path / "tree", files)
    output = tmp_path / "out"
    findings = FindingsRun("convert")
    context = ConversionContext(
        tree=tree,
        output=output,
        engine=SourceEngine.DOCBOOK,
        slug="str",
        version="11.2.1",
        product_name="TIBCO Streaming",
        api_roots=[tree / name for name in (api_roots or [])],
        output_roots=find_output_roots(tree, SourceEngine.DOCBOOK),
        findings=findings,
    )
    engine = DocBookEngine()
    units = []
    for root in engine.units(context):
        name = root.relative_to(tree).as_posix()
        context.assets = AssetCopier(root, SourceEngine.DOCBOOK, output / name if name else output)
        units.append(engine.convert_unit(context, root))
    return Run(units, findings, tree)


def one_page(tmp_path: Path, body: str, extra: Mapping[str, str] | None = None) -> Run:
    """A tree whose only guide holds one page. For the vocabulary tests."""
    return run(tmp_path, {
        "html/css/sbhelp.css": "body{}",
        "html/index.html": page("index.html", "StreamBase Documentation",
                                titlepage("StreamBase Documentation")),
        "html/authoring/index.html": page("authoring/index.html", "Authoring",
                                          titlepage("Authoring") + toc(entry("topic.html", "Topic"))),
        "html/authoring/topic.html": page("authoring/topic.html", "Topic",
                                          titlepage("Topic") + body),
        **(extra or {}),
    })


# -- the unit of work (§5.6.3) --------------------------------------------------


def test_the_unit_is_html_and_a_duplicate_directory_is_reported(tmp_path: Path) -> None:
    """A `str` version ships up to eight byte-identical duplicates of a guide.

    They hold DocBook pages, so a "holds a DocBook page" rule converts every
    duplicated guide twice. The stylesheet link is what separates them, and the
    rejection is reported rather than silent.
    """
    result = run(tmp_path, {
        "html/css/sbhelp.css": "body{}",
        "html/index.html": page("index.html", "Home", titlepage("Home")),
        "html/authoring/topic.html": page("authoring/topic.html", "Topic", titlepage("Topic")),
        # The duplicate: same bytes, one level up, linking a stylesheet that is
        # not under it.
        "authoring/topic.html": page("authoring/topic.html", "Topic", titlepage("Topic")),
    })

    assert [unit.name for unit in result.units] == ["html"]
    assert result.names() == ["authoring/topic.md", "index.md"]
    assert any("duplicate" in message for message in result.messages("DOCSET_SKIPPED"))


def test_output_mirrors_the_guide_directories(tmp_path: Path) -> None:
    """The guide directory is the only hierarchy this corpus has, so it is kept.

    Flat output would collide immediately: `index.html` alone is 24 pages in one
    version, one per guide.
    """
    result = run(tmp_path, {
        "html/css/sbhelp.css": "body{}",
        "html/index.html": page("index.html", "Home", titlepage("Home")),
        "html/welcome/index.html": page("welcome/index.html", "Welcome", titlepage("Welcome")),
        "html/authoring/index.html": page("authoring/index.html", "Authoring", titlepage("Authoring")),
    })

    assert result.names() == ["authoring/index.md", "index.md", "welcome/index.md"]


def test_the_landing_page_is_real_and_is_not_synthesized(tmp_path: Path) -> None:
    """`html/index.html` is a `div.book` with prose, not a frameset stub.

    The only engine of the four where `unit.landing` names a converted page rather
    than staying `None` for Phase 6 to fill.
    """
    result = one_page(tmp_path, "<p>Body.</p>")

    assert str(result.unit.landing) == "index.md"
    assert "index.md" in result.names()


