def test_the_book_toc_nests_and_a_part_page_does_not_duplicate_it(tmp_path: Path) -> None:
    """A book's TOC lists its parts; each part page carries a copy of its slice.

    The recursion is what reaches a section the book page never named; the filed
    guard is what stops the copy from placing everything twice.
    """
    result = run(tmp_path, {
        "html/css/sbhelp.css": "body{}",
        "html/index.html": page("index.html", "Home", titlepage("Home")),
        "html/authoring/index.html": page("authoring/index.html", "Authoring", (
            titlepage("Authoring")
            + toc(entry("part-one.html", "Part One", entry("alpha.html", "Alpha")))
        )),
        "html/authoring/part-one.html": page("authoring/part-one.html", "Part One", (
            titlepage("Part One")
            + toc(entry("alpha.html", "Alpha") + entry("beta.html", "Beta"))
        )),
        "html/authoring/alpha.html": page("authoring/alpha.html", "Alpha", titlepage("Alpha")),
        "html/authoring/beta.html": page("authoring/beta.html", "Beta", titlepage("Beta")),
    })

    assert result.under("Authoring") == ["Part One"]
    part = result.unit.nav[0].children[0]
    # Alpha comes from the book TOC's own nesting, Beta from the part page's --
    # and Alpha appears once, not once per TOC that names it.
    assert [child.label for child in part.children] == ["Alpha", "Beta"]
    assert "TOC_ORPHAN" not in result.codes()


